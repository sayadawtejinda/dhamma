const localizeSet = (cats, map, lang) => {
  if (lang !== 'en') return cats;
  return cats.map((c) => {
    const e = map[c.id];
    if (!e) return c;
    return {
      ...c,
      name: e[0],
      desc: e[1],
      names: c.names.map((nm, i) => (e[2][i] ? { ...nm, name: e[2][i][0], desc: e[2][i][1] } : nm)),
    };
  });
};

export const localizeAkusala = (cats, lang) => localizeSet(cats, AKUSALA_EN, lang);
export const localizeMissaka = (cats, lang) => localizeSet(cats, MISSAKA_EN, lang);
export const localizeBodhipakkhiya = (cats, lang) => localizeSet(cats, BODHI_EN, lang);
